import pandas as pd
import rqdatac
rqdatac.init()

from pathlib import Path
import json

folder_name = "LSV 模型"
save_dir = Path(f"factor_results/{folder_name}")
save_dir.mkdir(parents=True, exist_ok=True)
name = "lsv_daily_none_q10"
csv_path = save_dir / "lsv.csv"

# 读取：第 1 列为 date，其余列为股票代码
lsv_factor_data = pd.read_csv(
    csv_path,
    index_col=0,
    parse_dates=True,
)

# 规范化为米筐因子检验需要的格式
lsv_factor_data.index = pd.to_datetime(lsv_factor_data.index)
lsv_factor_data.index.name = "date"

lsv_factor_data.columns = (
    lsv_factor_data.columns.astype(str).str.strip()
)
lsv_factor_data.columns.name = "order_book_id"

lsv_factor_data = (
    lsv_factor_data
    .apply(pd.to_numeric, errors="coerce")
    .sort_index()
)

from rqfactor.notebook import factor_analysis

factor_df = lsv_factor_data
result = factor_analysis(
    f=factor_df,
    period=1,
    shift=1,
    rank_ic=True,
    quantile=10,
    ascending=True,
    winzorization="mad",
    normalization=False,
    neutralization="none",   # 先关闭：这是日频测试最常见的慢点
    include_st=False,
    include_new=False,
    benchmark="000985.XSHG",
)

print("回测已完成")

def save_result_item(name, value):
    """将米筐因子回测结果中的可用数据保存为 CSV。"""
    if value is None:
        print(f"跳过 {name}：结果为空")
        return

    if isinstance(value, pd.Series):
        value.rename(value.name or name).to_csv(
            save_dir / f"{name}.csv",
            index_label="date",
        )

    elif isinstance(value, pd.DataFrame):
        value.to_csv(save_dir / f"{name}.csv", index=True)

    elif isinstance(value, dict):
        pd.Series(value, name="value").to_csv(
            save_dir / f"{name}.csv",
            index_label="metric",
        )

    else:
        print(f"跳过 {name}：类型为 {type(value)}，不是表格数据")
        return

    print(f"已保存：{name}.csv")


# 米筐因子回测的核心原始结果
